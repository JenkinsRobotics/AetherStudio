// Actual built Studio UI against a disposable native host. No network mocking.
import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
const require=createRequire(new URL('../../core/files/package.json',import.meta.url));
const {chromium}=require('@playwright/test');
const [origin,cookie]=process.argv.slice(2);
const browser=await chromium.launch({headless:true});
try {
  const context=await browser.newContext();
  await context.addCookies([{name:'aether_native_session',value:cookie,url:origin,httpOnly:true,sameSite:'Strict'}]);
  const page=await context.newPage();
  page.setDefaultTimeout(15000);
  page.on('response',async response=>{if(response.url().endsWith('/api/admin/service') && !response.ok()) console.error('Service fixture HTTP failure',response.status(),await response.text());});
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto(origin+'/?workspace=admin');
  await page.getByRole('heading',{name:'Aether Studio Admin Center',exact:true}).waitFor();
  await page.goto(origin+'/?workspace=admin&section=server');
  await page.getByRole('heading',{name:'Server management',exact:true}).waitFor();
  await page.getByText('Aether Studio native host.',{exact:false}).waitFor();
  assert.equal(await page.getByRole('button',{name:'Prepare uninstall',exact:true}).count(),0);
  await page.goto(origin+'/?workspace=admin&section=teams');
  await page.getByRole('button',{name:'Create team',exact:true}).click();
  await page.getByLabel('Team name',{exact:true}).fill('Native browser operators');
  await page.getByRole('button',{name:'Save team',exact:true}).click();
  await page.getByRole('cell',{name:'Native browser operators',exact:true}).waitFor();
  await page.goto(origin+'/?workspace=admin&section=apps');
  let row=page.getByRole('row').filter({has:page.getByText('Aether Map',{exact:true})});
  await row.getByRole('button',{name:'Disable',exact:true}).click();
  await row.getByRole('button',{name:'Enable',exact:true}).waitFor();
  await row.getByRole('button',{name:'Enable',exact:true}).click();
  await row.getByRole('button',{name:'Disable',exact:true}).waitFor();
  await page.goto(origin+'/?workspace=admin&section=services');
  const form=page.locator('form').filter({has:page.getByRole('heading',{name:'Create a service account',exact:true})});
  await form.getByLabel('Name',{exact:true}).fill('Browser reporting service');
  await form.getByRole('checkbox',{name:'Aether Map',exact:true}).check();
  await form.getByRole('button',{name:'Create token',exact:true}).click();
  const key=await page.getByLabel('New service account token',{exact:true}).inputValue();
  assert.ok(key.startsWith('aether_sa_'));
  const catalogue=await fetch(origin+'/api/automation/commands/list',{method:'POST',headers:{'Content-Type':'application/json',Authorization:'Bearer '+key},body:'{}'});
  assert.equal(catalogue.status,200);
  assert.deepEqual((await catalogue.json()).apps,['map']);
  const serviceRow=page.getByRole('row').filter({has:page.getByRole('cell',{name:'Browser reporting service',exact:true})});
  await serviceRow.getByRole('button',{name:'Revoke',exact:true}).click();
  await serviceRow.getByRole('cell',{name:'Revoked / expired',exact:true}).waitFor();
  const revoked=await fetch(origin+'/api/automation/commands/list',{method:'POST',headers:{'Content-Type':'application/json',Authorization:'Bearer '+key},body:'{}'});
  assert.equal(revoked.status,401);
  await page.goto(origin+'/?workspace=admin&section=email');
  await page.getByRole('heading',{name:'Email delivery',exact:true}).waitFor();
  await page.getByRole('checkbox',{name:'Enable email delivery'}).check();
  await page.getByLabel('SMTP server',{exact:true}).fill('smtp.example.test');
  await page.getByLabel('Sender email',{exact:true}).fill('sender@example.test');
  await page.getByLabel('SMTP username',{exact:true}).fill('browser-sender');
  await page.getByLabel(/^SMTP password or app password/).fill('browser-only-private-password');
  await page.getByRole('button',{name:'Save email settings',exact:true}).click();
  await page.getByText('Configured',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Send test email',exact:true}).click();
  await page.getByRole('status').filter({hasText:'Test email queued.'}).waitFor();
  await page.goto(origin+'/?workspace=admin&section=activity');
  await page.getByRole('cell',{name:'mail test sent',exact:true}).waitFor();
  assert.equal((await page.locator('body').innerText()).includes('browser-only-private-password'),false);
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({browser:'Chromium',actualStudioAdmin:true,createTeam:true,disableEnableApp:true,saveMail:true,localTestDelivery:true,activity:true,serviceCreateUseRevoke:true,maintenance:true}));
} finally {await browser.close();}

"""Compose existing A marks with outlined Noto Sans wordmarks; never redraw marks.
Run from any directory. Requires fontTools. Raster proofs are rendered separately
from these SVG compositions by the browser, with no image generation or tracing.
"""
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
import base64, hashlib, json

HERE=Path(__file__).resolve().parent
ASSETS=HERE.parents[1]
APPS={"studio":"Studio","cad":"CAD","animation":"Animation","map":"Map","sketch":"Sketch","vector":"Vector","io":"IO","drive":"Drive","ui":"UI"}
ACCENTS={
 "studio":["#00a8ec","#0068c8","#53d9ff","#55a9ff"],
 "cad":["#009fff","#0058c6","#5cd5ff","#4c9dff"],
 "animation":["#8e65d7","#4953c7","#bca2ff","#7ab7ff"],
 "map":["#009fbd","#0961a4","#61e6e5","#60b5ff"],
 "sketch":["#75879a","#35475a","#d4dde6","#9eafc1"],
 "vector":["#2579e2","#5946c9","#75baff","#ad98ff"],
 "io":["#009caa","#087687","#6aefe0","#39bbda"],
 "drive":["#00a1d8","#0870b7","#7ce5ff","#4aafff"],
 "ui":["#168de7","#2762c4","#71cfff","#72a5ff"],
}
def outlines(text,weight,spacing):
 font=TTFont(ASSETS/f'fonts/noto-sans/NotoSans-{weight}.ttf');glyphs=font.getGlyphSet();cmap=font.getBestCmap();pen=SVGPathPen(glyphs);x=0
 for char in text:
  name=cmap[ord(char)];glyphs[name].draw(TransformPen(pen,(1,0,0,1,x,0)));x+=font['hmtx'][name][0]+spacing
 return {'path':pen.getCommands(),'advance':x-spacing}
word=outlines('Aether','Bold',-28)
layout={'height':160,'markSize':160,'textX':177,'baseline':111,'scale':.089,'gap':8}
products={app:{'name':name,'outline':outlines(name,'Regular',-15),'accents':ACCENTS[app]} for app,name in APPS.items()}
manifest={'created':'2026-10-16','composition':'Original transparent app A + outlined Noto Sans Bold Aether + Regular app name','fontLicense':'SIL Open Font License; ../../fonts/noto-sans/LICENSE','variants':[]}
for app,item in products.items():
 suffix_x=layout['textX']+word['advance']*layout['scale']+layout['gap'];width=round(suffix_x+item['outline']['advance']*layout['scale']+4,2);item['width']=width
 png=(HERE.parent/'marks'/f'{app}.png').read_bytes();image='data:image/png;base64,'+base64.b64encode(png).decode()
 for appearance in ['light','dark']:
  ink='#061b3e' if appearance=='light' else '#edf4fb';colors=item['accents'][:2] if appearance=='light' else item['accents'][2:]
  svg=f'''<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="160" viewBox="0 0 {width} 160" preserveAspectRatio="xMinYMid meet" role="img" aria-label="Aether {item['name']}"><title>Aether {item['name']}</title><defs><linearGradient id="accent" x1="0" y1="1" x2="0" y2="0"><stop stop-color="{colors[0]}"/><stop offset="1" stop-color="{colors[1]}"/></linearGradient></defs><image href="{image}" x="0" y="0" width="160" height="160"/><path d="{word['path']}" transform="translate(177 111) scale(.089 -.089)" fill="{ink}"/><path d="{item['outline']['path']}" transform="translate({suffix_x} 111) scale(.089 -.089)" fill="url(#accent)"/></svg>'''
  file=f'{app}-{appearance}.svg';(HERE/file).write_text(svg+'\n');manifest['variants'].append({'app':app,'appearance':appearance,'svg':file,'width':width,'height':160,'markSha256':hashlib.sha256(png).hexdigest(),'svgSha256':hashlib.sha256((HERE/file).read_bytes()).hexdigest()})
data={'word':word,'layout':layout,'apps':products}
(HERE/'data.ts').write_text('/** Generated by build.py from the existing marks and licensed Noto Sans fonts. */\nexport const appWordmarkData = '+json.dumps(data,indent=2)+' as const;\nexport type AppWordmarkName = keyof typeof appWordmarkData.apps;\n')
for item in manifest['variants']:
    png=HERE/f"{item['app']}-{item['appearance']}.png"
    if png.exists():
        item.update(png=png.name,pngSha256=hashlib.sha256(png.read_bytes()).hexdigest(),pngHeight=256)
(HERE/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
print('Composed 18 transparent SVGs; original mark bytes preserved.')

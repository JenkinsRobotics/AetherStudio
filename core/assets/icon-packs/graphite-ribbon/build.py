"""Build adaptive + standalone paired SVGs. Run from any directory; no dependencies.

Every tool has its own purpose-drawn master in masters/. pack.json is the
catalog and palette authority. This builder does not read or write any other
icon pack; undefined materials and missing masters are errors.
"""
from pathlib import Path
import json
import re

HERE = Path(__file__).resolve().parent
PACK = json.loads((HERE / 'pack.json').read_text())
PALETTES = PACK['palettes']

def color(key):
    return f'var(--graphite-{key},{PALETTES["dark"][key]})'

def gradient(name, a, b):
    return (f'<linearGradient id="{name}" x1="0" y1="0" x2=".7" y2="1">'
            f'<stop stop-color="{color(a)}"/><stop offset="1" stop-color="{color(b)}"/>'
            '</linearGradient>')

DEFS = '<defs>' + ''.join(gradient(name, a, b) for name,a,b in [
    ('top','top-a','top-b'), ('front','front-a','front-b'),
    ('side','side-a','side-b'), ('accent','blue-a','blue-b')])
DEFS += (f'<radialGradient id="sphere" cx=".3" cy=".22" r=".8">'
         f'<stop stop-color="{color("sphere-a")}"/>'
         f'<stop offset=".48" stop-color="{color("sphere-b")}"/>'
         f'<stop offset="1" stop-color="{color("sphere-c")}"/></radialGradient></defs>')

def artwork(name):
    # Every icon must have a deliberate Graphite master. Never silently inherit
    # another pack's geometry or material definitions.
    body = (HERE / 'masters' / f'{name}.svg').read_text().strip()
    body = re.sub(r'(stroke|fill)="(edge|muted|blue|cavity)"',
                  lambda m: f'{m[1]}="{color(m[2])}"', body)
    references = set(re.findall(r'url\(#([^)]+)\)', body))
    definitions = re.findall(r'<(?:linearGradient|radialGradient)\b.*?</(?:linearGradient|radialGradient)>', DEFS)
    used = [definition for definition in definitions
            if re.search(r'id="([^"]+)"', definition)[1] in references]
    known = {re.search(r'id="([^"]+)"', definition)[1] for definition in used}
    if references != known:
        raise ValueError(f'{name}: undefined material {references - known}')
    return ('<defs>' + ''.join(used) + '</defs>' if used else '') + body

names = PACK['icons']
if set(names) != {file.stem for file in (HERE / 'masters').glob('*.svg')}:
    raise ValueError('Catalog and Graphite masters must match exactly')
for directory in ['adaptive','light','dark']:
    (HERE / directory).mkdir(exist_ok=True)
for name in names:
    svg = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32" fill="none" '
           f'stroke="{color("edge")}" stroke-width="1.15" stroke-linecap="round" '
           f'stroke-linejoin="round">{artwork(name)}</svg>\n')
    (HERE/'adaptive'/f'{name}.svg').write_text(svg)
    for palette in ['light','dark']:
        standalone = re.sub(r'var\(--graphite-([^,]+),[^)]+\)',
                            lambda m: PALETTES[palette][m[1]], svg)
        (HERE/palette/f'{name}.svg').write_text(standalone)
imports = '\n'.join(f'import icon{i} from "./adaptive/{name}.svg?raw";' for i,name in enumerate(names))
registry = '\n'.join(f'  "{name}": icon{i},' for i,name in enumerate(names))
(HERE/'artwork.ts').write_text('// Generated by build.py from pack.json; SVG artwork stays in core/assets.\n'+imports+'\nexport const graphiteRibbonArtwork = {\n'+registry+'\n} as const;\n')
print(f'Built {len(names)} icons × adaptive/light/dark.')

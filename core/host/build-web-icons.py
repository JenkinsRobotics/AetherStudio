"""Render the selected Core app artwork; never replace it with toolbar glyphs."""

import argparse
import base64
import hashlib
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

root = Path(__file__).resolve().parents[2]
parser = argparse.ArgumentParser()
parser.add_argument("--variant", choices=("new", "fancy", "simple"), default="new")
apps = ("studio", "cad", "animation", "ui", "map", "sketch", "vector", "io", "drive")
parser.add_argument("--apps", nargs="+", choices=apps, default=apps)
args = parser.parse_args()
output = root / "core/assets/branding/apps"
# Original artwork and earlier browser icons are preserved in sibling archives.
sources = {}
for app in args.apps:
    vector = output / f"{app}.svg"
    if args.variant == "new" or app in ("map", "sketch", "vector", "io", "drive"):
        mark = "animate" if app == "animation" else app
        source = root / f"core/assets/branding/new-aether-2026-09/aether-{mark}.png"
    else:
        if app != "ui":
            shutil.copyfile(root / f"core/assets/branding/{args.variant}/{app}.svg", vector)
        source = vector
    target = output / f"{app}.png"
    subprocess.run(
        ["sips", "-z", "512", "512", "-s", "format", "png", str(source), "--out", str(target)],
        check=True,
        stdout=subprocess.DEVNULL,
    )
    # Apply the same rounded app silhouette as AppIcon to the browser/OS PNG.
    # This is a presentation mask: keep the source artwork unchanged inside it.
    with tempfile.TemporaryDirectory(prefix="aether-icon-mask-") as temporary:
        mask = Path(temporary) / "icon.svg"
        encoded = base64.b64encode(target.read_bytes()).decode()
        mask.write_text(
            '<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="512" height="512" viewBox="0 0 512 512">'
            '<defs><clipPath id="app"><rect width="512" height="512" rx="112.64"/></clipPath></defs>'
            f'<image width="512" height="512" clip-path="url(#app)" xlink:href="data:image/png;base64,{encoded}"/>'
            '</svg>'
        )
        subprocess.run(
            ["sips", "-s", "format", "png", str(mask), "--out", str(target)],
            check=True, stdout=subprocess.DEVNULL,
        )
    if app == "io":
        # Serve the shared identity at its canonical URL during standalone dev.
        public_icons = root / "aether-io/public/icons"
        public_icons.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(target, public_icons / "io.png")
for app in apps:
    target = output / f"{app}.png"
    if target.is_file():
        digest = hashlib.sha256(target.read_bytes()).hexdigest()[:12]
        sources[app] = f"/icons/{app}.png?v={digest}"
(output / "sources.ts").write_text(
    "// Generated by core/host/build-web-icons.py from the active PNG bytes.\n"
    + "export const appIconSources = " + json.dumps(sources, indent=2) + " as const;\n"
)
subprocess.run([sys.executable, str(Path(__file__).with_name("build-favicons.py")), "--apps", *args.apps], check=True)
print(f"Updated {len(args.apps)} active app icons, tab icons and versioned source URLs.")
